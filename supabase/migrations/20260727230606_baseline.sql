create or replace function public.cleanup_expired_oauth_tokens()
returns integer
language plpgsql
set search_path to ''
as $function$
declare
  deleted_count integer;
begin
  delete from public.oauth_tokens
  where grant_type is distinct from 'authorization_code'
    and (
      (revoked_at is not null and revoked_at < now() - interval '7 days')
      or (
        revoked_at is null
        and refresh_token_expires_at is not null
        and refresh_token_expires_at < now()
      )
    );

  get diagnostics deleted_count = row_count;
  return deleted_count;
end;
$function$;


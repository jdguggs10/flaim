    mode() within group (order by client_name) as client,
    min(ts) as first_ts
  from public.mcp_tool_events
  where env = 'prod'
    and auth_type = 'oauth'
    and user_id not in (select user_id from analytics.internal_users)
  group by user_id
),
ranked as (
  select
    row_number() over (order by calls desc) as rank,
    calls,
    client,
    first_ts,
    sum(calls) over () as total
  from per_user
)
select
  rank::integer as rank,
  calls::integer as calls,
  round(100.0 * calls::numeric / total, 1) as pct_of_calls,
  round(
    100.0 * sum(calls) over (order by rank) / total,
    1
  ) as cumulative_pct,
  client,
  to_char(first_ts at time zone 'America/New_York', 'Mon DD') as first_seen
from ranked
order by rank
limit 15;


begin
  delete from public.mcp_user_daily
  where day = target_day;

  insert into public.mcp_user_daily (
    day,
    env,
    user_id,
    auth_type,
    client_name,
    call_count
  )
  select
    target_day,
    env,
    user_id,
    auth_type,
    coalesce(client_name, ''),
    count(*)
  from public.mcp_tool_events
  where ts >= target_day
    and ts < target_day + 1
  group by env, user_id, auth_type, coalesce(client_name, '');

  delete from public.mcp_tool_daily
  where day = target_day;

  insert into public.mcp_tool_daily (
    day,
    env,
    auth_type,
    tool_name,
    platform,
    sport,
    status,
    call_count,
    p50_ms,
    p95_ms
  )
  select
    target_day,
    env,
    auth_type,
    tool_name,
    coalesce(platform, ''),
    coalesce(sport, ''),
    status,
    count(*),
    percentile_cont(0.5) within group (order by latency_ms)::integer,
    percentile_cont(0.95) within group (order by latency_ms)::integer
  from public.mcp_tool_events
  where ts >= target_day
    and ts < target_day + 1
  group by
    env,
    auth_type,
    tool_name,
    coalesce(platform, ''),
    coalesce(sport, ''),
    status;

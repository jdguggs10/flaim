create or replace function public.acquire_public_chat_run(
  p_visitor_key text,
  p_preset_id text,
  p_model text,
  p_max_concurrent integer default 1
)
returns table (
  allowed boolean,
  run_id uuid,
  rejection_reason text,
  concurrent_count integer
)
language plpgsql
set search_path to ''
as $function$
declare
  v_run_id uuid;
  v_concurrent_count integer;
begin
  perform pg_advisory_xact_lock(hashtext(p_visitor_key));

  update public.chat_runs
  set status = 'aborted',
      error_code = coalesce(error_code, 'stale_timeout'),
      completed_at = coalesce(completed_at, now()),
      updated_at = now()
  where visitor_key = p_visitor_key
    and status = 'running'
    and started_at < now() - interval '5 minutes';

  select count(*) into v_concurrent_count
  from public.chat_runs
  where visitor_key = p_visitor_key
    and status = 'running';

  if v_concurrent_count >= p_max_concurrent then
    insert into public.chat_runs (visitor_key, preset_id, model, status)
    values (p_visitor_key, p_preset_id, p_model, 'concurrency_rejected')
    returning id into v_run_id;

    return query
      select false, v_run_id, 'concurrency_limited', v_concurrent_count;
    return;
  end if;

  insert into public.chat_runs (visitor_key, preset_id, model, status)
  values (p_visitor_key, p_preset_id, p_model, 'running')
  returning id into v_run_id;

  return query
    select true, v_run_id, null::text, v_concurrent_count;
end;
$function$;


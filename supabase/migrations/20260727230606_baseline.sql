create or replace function analytics.dashboard_payload(
  include_internal boolean
)
returns jsonb
language sql
stable
set search_path to ''
as $function$
with excluded as (
  select user_id
  from analytics.internal_users
  where not include_internal
)
select jsonb_build_object(
  'usage_trend',
  (
    select coalesce(jsonb_agg(u order by u.et_day), '[]'::jsonb)
    from (
      with ev as (
        select distinct
          user_id as uid,
          (ts at time zone 'America/New_York')::date as et_day
        from public.mcp_tool_events
        where env = 'prod'
          and auth_type = 'oauth'
          and user_id is not null
          and user_id not in (select user_id from excluded)
      ),
      firsts as (
        select uid, min(et_day) as first_day
        from ev
        group by uid
      ),
      daily as (
        select et_day, count(distinct uid) as dau
        from ev
        group by et_day
      ),
      newd as (
        select first_day as et_day, count(*) as new_users
        from firsts
        group by first_day
      ),
      bounds as (
        select min(et_day) as lo, max(et_day) as hi
        from ev
      ),
      days as (
        select generate_series(lo, hi, interval '1 day')::date as et_day
        from bounds
        where lo is not null
      )
      select
        d.et_day::text as et_day,
        coalesce(da.dau, 0)::integer as dau,
        (
          select count(distinct e.uid)::integer
          from ev e
          where e.et_day > d.et_day - 7
            and e.et_day <= d.et_day
        ) as wau_7d,
        coalesce(nw.new_users, 0)::integer as new_users,
        (coalesce(da.dau, 0) - coalesce(nw.new_users, 0))::integer
          as returning_users
      from days d
      left join daily da on da.et_day = d.et_day
      left join newd nw on nw.et_day = d.et_day
    ) u
  ),
  'retention_weekly',
  (
    select coalesce(jsonb_agg(rw order by rw.week_start), '[]'::jsonb)
    from (
      with evd as (
        select distinct
          user_id as uid,
          (ts at time zone 'America/New_York')::date as et_day
        from public.mcp_tool_events
        where env = 'prod'
          and auth_type = 'oauth'
          and user_id is not null
          and user_id not in (select user_id from excluded)
      ),
      ev as (
        select distinct uid, date_trunc('week', et_day)::date as wk
        from evd
      ),
      this_wk as (
        select date_trunc(
          'week',
          now() at time zone 'America/New_York'
        )::date as wk
      ),
      bounds as (
        select
          min(et_day) as first_day,
          date_trunc('week', min(et_day))::date as first_wk
        from evd
      ),
      weeks as (
        select generate_series(
          first_wk,
          (select wk from this_wk),
          interval '7 days'
        )::date as wk
        from bounds
        where first_wk is not null
      ),
      cohorts as (
        select wk, count(*) as queriers
        from ev
        group by wk
      ),
      returns as (
        select e.wk, count(*) as returned
        from ev e
        where exists (
          select 1
          from ev n
          where n.uid = e.uid
            and n.wk = e.wk + 7
        )
        group by e.wk
      )
      select
        w.wk::text as week_start,
        coalesce(c.queriers, 0)::integer as queriers,
        case
          when w.wk >= t.wk then null
          else coalesce(r.returned, 0)::integer
        end as returned_next,
        case
          when w.wk >= t.wk then null
          else round(
            100.0
              * coalesce(r.returned, 0)
              / nullif(c.queriers, 0),
            1
          )
        end as return_pct,
        (w.wk < (select first_day from bounds)) as week_partial_start,
        (w.wk >= t.wk) as week_open,
        (w.wk < t.wk and w.wk + 7 >= t.wk) as next_week_open
      from weeks w
      cross join this_wk t
      left join cohorts c on c.wk = w.wk
      left join returns r on r.wk = w.wk
    ) rw
  ),
  'totals',
  (
    select to_jsonb(t)
    from (
      select
        count(distinct user_id) filter (
          where (ts at time zone 'America/New_York')
            >= date_trunc(
              'year',
              now() at time zone 'America/New_York'
            )
        )::integer as ytd_users,
        count(distinct user_id)::integer as alltime_users,
        count(*) filter (
          where (ts at time zone 'America/New_York')
            >= date_trunc(
              'year',
              now() at time zone 'America/New_York'
            )
        )::integer as ytd_calls,
        count(*)::integer as alltime_calls
      from public.mcp_tool_events
      where env = 'prod'
        and auth_type = 'oauth'
        and user_id is not null
        and user_id not in (select user_id from excluded)
    ) t
  ),
  'funnel',
  (
    select coalesce(jsonb_agg(f order by f.sort_order), '[]'::jsonb)
    from (
      with oauth as (
        select distinct user_id as uid
        from public.oauth_tokens
        where user_id is not null
          and user_id not in (select user_id from excluded)
      ),
      creds as (
        select uid
        from (
          select clerk_user_id as uid
          from public.espn_credentials
          where clerk_user_id is not null
          union
          select clerk_user_id
          from public.yahoo_credentials
          where clerk_user_id is not null
          union
          select clerk_user_id
          from public.sleeper_connections
          where clerk_user_id is not null
        ) c
        where uid not in (select user_id from excluded)
      ),
      leagues as (
        select uid
        from (
          select clerk_user_id as uid
          from public.espn_leagues
          where clerk_user_id is not null
          union
          select clerk_user_id
          from public.yahoo_leagues
          where clerk_user_id is not null
          union
          select clerk_user_id
          from public.sleeper_leagues
          where clerk_user_id is not null
        ) l
        where uid not in (select user_id from excluded)
      ),
      queried as (
        select distinct user_id as uid
        from public.mcp_tool_events
        where env = 'prod'
          and auth_type = 'oauth'
          and user_id is not null
          and user_id not in (select user_id from excluded)
      ),
      known as (
        select uid from oauth
        union select uid from creds

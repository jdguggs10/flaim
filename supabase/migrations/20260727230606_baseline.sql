create view analytics.usage_daily as
with ev as (
  select
    user_id,
    ts,
    (ts at time zone 'America/New_York')::date as et_day
  from public.mcp_tool_events
  where env = 'prod'
    and auth_type = 'oauth'
    and user_id not in (select user_id from analytics.internal_users)
),
firsts as (
  select
    user_id,
    min((ts at time zone 'America/New_York')::date) as first_day
  from ev
  group by user_id
),
daily as (
  select
    et_day,
    count(distinct user_id) as real_queriers,
    count(*) as calls,
    min(ts) as first_ev,
    max(ts) as last_ev
  from ev
  group by et_day
),
new_faces as (
  select first_day as et_day, count(*) as new_faces
  from firsts
  group by first_day
)
select
  d.et_day,
  d.real_queriers,
  d.calls,
  to_char(d.first_ev at time zone 'America/New_York', 'HH24:MI') as first_ev_et,
  to_char(d.last_ev at time zone 'America/New_York', 'HH24:MI') as last_ev_et,
  coalesce(n.new_faces, 0::bigint) as new_faces,
  sum(coalesce(n.new_faces, 0::bigint)) over (
    order by d.et_day
  ) as cumulative_distinct
from daily d
left join new_faces n using (et_day);

